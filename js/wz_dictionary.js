/**
 * ============================================================================
 * @component   DictionaryNormalizerAndHint (UPDATE v4.3)
 * @doclogger   - normalizeAlphaWord: Lược bỏ dấu cách & dấu gạch nối ('last-minute'
 *                -> 'lastminute', 'on the corner' -> 'onthecorner') để người chơi
 *                gõ liền không cần bận tâm ký tự phân cách.
 *              - formatWordHint: Giữ nguyên dấu '-' và khoảng tách từ khi in lên
 *                nắp gỗ (VD: 'l _ _ _ - _ _ _ _ _ _'), chỉ đếm các ký tự chữ cái
 *                thực tế để mở khóa dần theo tiến độ gõ.
 * ============================================================================
 */
// .replace(/[^a-z0-9]/g, ''): Biểu thức chính quy (Regex) tìm mọi ký tự KHÔNG PHẢI
// chữ cái a-z hoặc số 0-9 (như dấu cách ' ', dấu gạch nối '-') và xóa sạch trên toàn chuỗi (cờ g).
// Mục đích: Biến 'last-minute' -> 'lastminute' để so khớp khi người chơi gõ liền.
export function normalizeAlphaWord(rawWord = '') {
  return rawWord.toLowerCase().replace(/[^a-z0-9]/g, '');
}

export function formatWordHint(enWord = '', revealedLetterCount = 1) {
  const cleanDisplay = enWord.toLowerCase().trim();
  if (!cleanDisplay) return '';

  const totalLetters = normalizeAlphaWord(cleanDisplay).length;
  const safeReveal = Math.min(Math.max(1, revealedLetterCount), Math.max(1, totalLetters));

  let letterIndex = 0;
  return cleanDisplay
    .split('')
    .map((char) => {
      if (char === '-') return '-';
      if (char === ' ') return '\u00A0\u00A0'; // Giữ khoảng tách giữa 2 từ không bị HTML gộp dấu cách
      const isShown = letterIndex < safeReveal;
      letterIndex += 1;
      return isShown ? char : '_';
    })
    .join(' ');
}